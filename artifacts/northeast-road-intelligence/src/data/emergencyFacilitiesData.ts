/**
 * Haversine formula to compute great-circle distance in kilometers
 */
export function calculateDistanceKm(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 6371; // Earth's radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const d = R * c;
  return Math.round(d * 10) / 10;
}

/**
 * Estimate road driving time based on mountainous vs plains terrain
 */
export function estimateRoadEta(distanceKm: number, isMountainTerrain = true): string {
  // Mountainous speeds average ~25-35 km/h; Plains ~45-60 km/h
  const avgSpeed = isMountainTerrain ? 28 : 50;
  const hours = distanceKm / avgSpeed;
  const totalMinutes = Math.max(2, Math.round(hours * 60));

  if (totalMinutes < 60) {
    return `~${totalMinutes} mins`;
  }
  const h = Math.floor(totalMinutes / 60);
  const m = totalMinutes % 60;
  return `~${h}h ${m > 0 ? `${m}m` : ''}`;
}

/**
 * Generate direct Google Maps direction navigation link
 */
export function getDirectionsUrl(lat: number, lng: number, userLat?: number, userLng?: number): string {
  if (userLat && userLng) {
    return `https://www.google.com/maps/dir/?api=1&origin=${userLat},${userLng}&destination=${lat},${lng}&travelmode=driving`;
  }
  return `https://www.google.com/maps/dir/?api=1&destination=${lat},${lng}&travelmode=driving`;
}
